//! Plugin that removes duplicate identical JOIN clauses from query ASTs.

use smallvec::SmallVec;
use std::sync::Arc;

use crate::operation_node::transformer::OperationNodeTransformer;
use crate::operation_node::*;
use crate::plugin::traits::KyselyPlugin;
use crate::util::QueryId;

/// AST transformer that deduplicates identical JOIN clauses on SELECT queries.
struct DeduplicateJoinsTransformer;

impl OperationNodeTransformer for DeduplicateJoinsTransformer {
    fn transform_select_query(
        &mut self,
        node: &SelectQueryNode,
        _orig: &Arc<OperationNode>,
    ) -> Arc<OperationNode> {
        let mut unique_joins = SmallVec::<[Arc<OperationNode>; 2]>::new();
        for join in &node.joins {
            let transformed_join = self.transform_node(Arc::clone(join));
            if !unique_joins.contains(&transformed_join) {
                unique_joins.push(transformed_join);
            }
        }

        let mut new_node = node.clone();
        new_node.joins = unique_joins;

        if let Some(ref from) = node.from {
            new_node.from = Some(self.transform_node(Arc::clone(from)));
        }
        if let Some(ref where_clause) = node.where_clause {
            new_node.where_clause = Some(self.transform_node(Arc::clone(where_clause)));
        }
        if let Some(ref with) = node.with {
            new_node.with = Some(self.transform_node(Arc::clone(with)));
        }
        if let Some(ref having) = node.having {
            new_node.having = Some(self.transform_node(Arc::clone(having)));
        }

        Arc::new(OperationNode::SelectQuery(new_node))
    }
}

/// Plugin removing identical duplicate JOIN clauses generated by dynamic queries.
// @spec REQ-PLUG-004
#[derive(Debug, Clone, Copy, Default)]
pub struct DeduplicateJoinsPlugin;

impl DeduplicateJoinsPlugin {
    /// Creates a new `DeduplicateJoinsPlugin`.
    pub fn new() -> Self {
        Self
    }
}

impl KyselyPlugin for DeduplicateJoinsPlugin {
    fn transform_query(&self, node: Arc<OperationNode>, _query_id: QueryId) -> Arc<OperationNode> {
        let mut transformer = DeduplicateJoinsTransformer;
        transformer.transform_node(node)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::dialect::CustomDialect;
    use crate::driver::{DatabaseConnection, Driver, DriverError};
    use crate::kysely::Kysely;
    use crate::query_compiler::{CompiledQuery, DefaultQueryCompiler};
    use crate::query_executor::QueryResult;
    use std::sync::Mutex;

    struct JoinRecordingConn {
        queries: Arc<Mutex<Vec<String>>>,
    }

    #[async_trait::async_trait]
    impl DatabaseConnection for JoinRecordingConn {
        async fn execute_query(
            &mut self,
            query: &CompiledQuery,
        ) -> Result<QueryResult, DriverError> {
            self.queries.lock().unwrap().push(query.sql.clone());
            Ok(QueryResult::default())
        }
    }

    struct JoinRecordingDriver {
        queries: Arc<Mutex<Vec<String>>>,
    }

    #[async_trait::async_trait]
    impl Driver for JoinRecordingDriver {
        async fn acquire_connection(&self) -> Result<Box<dyn DatabaseConnection>, DriverError> {
            Ok(Box::new(JoinRecordingConn {
                queries: Arc::clone(&self.queries),
            }))
        }

        async fn release_connection(
            &self,
            _connection: Box<dyn DatabaseConnection>,
        ) -> Result<(), DriverError> {
            Ok(())
        }

        async fn destroy(&self) -> Result<(), DriverError> {
            Ok(())
        }
    }

    #[tokio::test]
    async fn test_deduplicate_joins_plugin() {
        let queries = Arc::new(Mutex::new(Vec::new()));
        let driver = Arc::new(JoinRecordingDriver {
            queries: Arc::clone(&queries),
        });
        let compiler = Arc::new(DefaultQueryCompiler::new());
        let dialect = CustomDialect::new(driver, compiler);

        let db = Kysely::new(dialect).with_plugin(DeduplicateJoinsPlugin::new());

        // Build query adding the identical join twice (simulating dynamic query builders)
        let _ = db
            .select_from("orders")
            .select(["orders.id", "users.name"])
            .inner_join("users", |join| join.on("users.id", "=", "orders.user_id"))
            .inner_join("users", |join| join.on("users.id", "=", "orders.user_id"))
            .execute()
            .await;

        let recorded = queries.lock().unwrap();
        assert_eq!(recorded.len(), 1);
        let sql = &recorded[0];

        // Count occurrences of "JOIN"
        let join_count = sql.matches("JOIN").count();
        assert_eq!(
            join_count, 1,
            "Expected only 1 JOIN after deduplication, got: {sql}"
        );
    }
}
